import fs from 'node:fs';
import assert from 'node:assert/strict';
import { uniqueById, groupByCause, sameCause } from '../src/lib/kb/causes.ts';
import { DEDUPE_CASES } from '../src/lib/kb/dedupe-cases.ts';
import { deskRef } from '../src/lib/kb/desk-ref.ts';
const read = (p) => JSON.parse(fs.readFileSync(p, 'utf8'));
const base = 'src/lib/data/';
const raw = read(base + 'reports-4471.json');
const tenants = fs.readdirSync(base + 'tenants').map((p) => read(base + 'tenants/' + p));
const tenantOf = (r) => tenants.find((t) => t.handle === r.tenant);
const unique = uniqueById(raw);
const merged = unique.filter((r) => r.mergedInto === 4471);
const groups = groupByCause(merged, tenantOf);
const counts = Object.fromEntries(groups.map((g) => [g.cause, g.reports.length]));
assert.equal(raw.length, 427);
assert.equal(unique.length, 412);
assert.deepEqual(counts, { parser: 379, hint: 33 });
assert.equal(groups.reduce((n, g) => n + g.reports.length, 0), merged.length);
const cases = DEDUPE_CASES.map((c) => ({case: c.why, sameCause: sameCause(c.a, tenantOf(c.a), c.b, tenantOf(c.b))}));
assert.deepEqual(cases.map((c) => c.sameCause), [true, false, false, true, false]);
const reviewSource = fs.readFileSync('src/routes/kb/incidents/4471-review/+page.svx', 'utf8');
const signature = reviewSource.match(/^signature: '([^']+)'$/m)?.[1];
assert.ok(signature?.startsWith('v1.'), 'Missing course signature in review frontmatter');
const result = { exportedAt: '2026-10-04', reviewed: '2026-10-29', rawRows: raw.length, uniqueReports: unique.length, mergedReports: merged.length, duplicateRows: raw.length - unique.length, groups: groups.map(({reports, ...g}) => ({...g, count: reports.length, issue: g.cause === 'parser' ? 1 : 2, reportIds: reports.map((r) => r.id)})), needsVerification: read(base + 'desk-notes.json').oneDayMove, cases, deskRef: deskRef(signature) };
fs.mkdirSync('rendered', { recursive: true });
fs.writeFileSync('rendered/audit.json', JSON.stringify(result, null, 2) + '\n');
console.log(JSON.stringify({ raw: raw.length, unique: unique.length, counts, deskRef: result.deskRef }));
